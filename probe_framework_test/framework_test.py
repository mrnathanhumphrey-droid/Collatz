"""
framework_test.py
=================
Test whether the Diaconis-Graham 1992 / CDG / DS-C 1994 Fourier framework
applies to K_k on (Z/3^k)*.

Key prediction (DG framework, iid case): Q̂_n(χ) = F(χ)^n for some F(χ)
independent of (r0, n, ...). Equivalent: the ratio
    F_n(r0, χ) := Q̂_n(χ) / Q̂_{n-1}(χ)
is constant in n and r0.

When the dynamics is X → a·X + ε with shift-invariant transition kernel
on (Z/3^k)*, characters χ are eigenvectors of K and F_n collapses to the
single eigenvalue. K_k = (3X+1)·2^(-V) is NOT shift-invariant: the +1
breaks shift symmetry. The test asks whether the breakage is "small"
(framework applies with modification) or "large" (framework fails).

Phase 1: Compute Q̂_n(χ) = ⟨χ̄, K^n δ_r0⟩ for r0 ∈ several test points,
         χ ∈ all characters of (Z/3^k)*, n=1..10.
Phase 2: Compute F_n(r0, χ) = Q̂_n / Q̂_{n-1}; test stability in n and r0.
Phase 3: Cayley graph diameter and growth for (Z/3^k)*, generators {2, 2^-1}.
Phase 4: Outcome decision.

Output:
  Q_hat_per_character_k{k}.csv
  product_structure_test_k{k}.csv
  moderate_growth_test_k{k}.csv
  framework_findings.md
"""
from __future__ import annotations

import csv
import sys
import time
from pathlib import Path

import numpy as np

sys.path.insert(0, r"C:\Collatz\probe_epsilon_12")
sys.path.insert(0, r"C:\Collatz\probe_ayyer_singla_test")
from compute_epsilon_12 import MatVecK  # noqa
