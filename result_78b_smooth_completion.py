"""
result_78b_smooth_completion.py — explore the smooth-completion gambit.

Strategy: instead of Cochrane Theorem 2 directly, we:
1. Compute |S_{r,ℓ,ε}(m)| empirically for r = 2..6, ℓ ∈ {0,1,2}, ε ∈ {0,1}, m ∈ Z/N_r
2. Look at empirical size — is it O(N^{1/2}) (square root cancellation)? O(N^{α}) for α < 1/2?
3. Try smooth-completion: lift mod M = 3^{r+1} · q for auxiliary prime q
4. Compare bounds

Concretely: Kalafatelis's eq 190 needs ||ĥ_{r,ℓ}||_{ℓ¹(J)} ≪ √η · N · η^{δ} for some δ > 0.
This requires sup_m |ĥ_{r,ℓ}(m)| · |J| ≪ √η · N · η^δ on a window |J| ≪ √η · N.
Equivalently sup_m |ĥ_{r,ℓ}(m)| ≪ N · η^δ / something.

If |S_{r,ℓ,ε}(m)| = O(N^α) for α < 1, we get progress. Want α ≤ 1/2 for full saving.
"""
import sys
import os
import math
import cmath
import numpy as np

sys.stdout.reconfigure(encoding="utf-8")
OUTDIR = r"C:\Collatz\experiments_output"
os.makedirs(OUTDIR, exist_ok=True)


def compute_S(r, ell_phase, eps, m):
    """S_{r,ℓ,ε}(m) = Σ_{u=0}^{3^{r-1}-1} e_{3^{r+1}}(c_{ℓ,ε} · 4^u - 9mu)
    where c_{ℓ,ε} = 2^ε · ω_r^ℓ.

    For our purposes, model c_{ℓ,ε} as a fixed unit; we compute for c = 1, 2 (ε = 0, 1)
    and ω_r as a primitive cube root in (Z/3^{r+1})*.

    A primitive cube root of unity in (Z/3^{r+1})* exists since 3 | φ(3^{r+1}) = 2·3^r.
    The cube root corresponds to (Z/3^{r+1})* /^3 structure. Here we model ω_r^ℓ for ℓ=0,1,2
    as 1, ζ, ζ² where ζ ∈ (Z/3^{r+1})* satisfies ζ^3 = 1.

    For a concrete realization: ζ exists since the cyclic group (Z/3^{r+1})* of order 2·3^r
    has a unique subgroup of order 3 (since 3 | 2·3^r). This subgroup contains ω_r.
    """
    N_phase = 3**(r+1)
    N_range = 3**(r-1)

    # Find a primitive cube root of unity in (Z/N_phase)*
    # ω_r satisfies ω_r^3 = 1 and ω_r ≠ 1
    # In (Z/3^{r+1})*, the order-3 subgroup is generated by some ω_r.
    # By computation: the 3-Sylow of (Z/3^{r+1})* is the principal unit subgroup 1 + 3Z/3^{r+1}.
    # An order-3 element of this subgroup has the form 1 + a·3^r for some a ∈ {1, 2}.
    # Specifically: (1 + 3^r)^3 = 1 + 3·3^r + 3·3^{2r} + 3^{3r} ≡ 1 mod 3^{r+1} (for r ≥ 1).
    # Wait need to check: 1 + 3·3^r = 1 + 3^{r+1} ≡ 1 mod 3^{r+1}. ✓
    # And 3·3^{2r} = 3^{2r+1} ≡ 0 mod 3^{r+1} for r ≥ 1 (since 2r+1 ≥ r+1).
    # So (1 + 3^r)^3 ≡ 1 mod 3^{r+1}. Yes.

    omega_r = 1 + 3**r  # primitive cube root of unity (verify (1+3^r)^3 ≡ 1 mod 3^{r+1})
    # Verify
    omega_cubed = pow(omega_r, 3, N_phase)
    if omega_cubed != 1:
        # try another candidate
        omega_r = 1 + 2*(3**r)
        omega_cubed = pow(omega_r, 3, N_phase)
        assert omega_cubed == 1, f"omega_r^3 = {omega_cubed}, expected 1 mod {N_phase}"

    c_eps = pow(2, eps, N_phase)
    c_ell_eps = (c_eps * pow(omega_r, ell_phase, N_phase)) % N_phase

    total = complex(0, 0)
    pow_4 = 1
    for u in range(N_range):
        # 4^u mod N_phase
        # phase = (c_ell_eps * pow_4 - 9*m*u) mod N_phase, then divide by N_phase
        phase_int = (c_ell_eps * pow_4 - 9 * m * u) % N_phase
        total += cmath.exp(2j * cmath.pi * phase_int / N_phase)
        pow_4 = (pow_4 * 4) % N_phase
    return total


def main():
    print("# R78b: smooth-completion exploration — empirical S_{r,ℓ,ε}(m) sizes")
    print()

    print("# Empirical |S_{r,ℓ,ε}(m)| analysis at r = 2..5")
    print()

    for r in [2, 3, 4, 5]:
        N_phase = 3**(r+1)
        N_range = 3**(r-1)
        # N_r in Kalafatelis's notation = 2·3^{r-1} (he uses this)
        N_r = 2 * 3**(r-1)
        print(f"## r = {r}: range N = {N_range}, modulus 3^{r+1} = {N_phase}, N_r = 2·3^(r-1) = {N_r}")

        # Sample over (ℓ, ε, m) — collect |S| values
        S_vals = []
        for ell in range(3):  # ℓ = 0, 1, 2
            for eps in [0, 1]:
                for m in range(N_r):
                    S = compute_S(r, ell, eps, m)
                    S_vals.append(abs(S))

        S_arr = np.array(S_vals)
        print(f"  Computed {len(S_vals)} values of |S_{{r,ℓ,ε}}(m)|.")
        print(f"  max |S| = {S_arr.max():.6f}, mean |S| = {S_arr.mean():.6f}, median |S| = {np.median(S_arr):.6f}")
        print(f"  Trivial bound = N = {N_range}")
        # Square-root saving check
        sqrt_N = math.sqrt(N_range)
        print(f"  √N = {sqrt_N:.4f},  max |S|/√N = {S_arr.max()/sqrt_N:.4f},  max |S|/N = {S_arr.max()/N_range:.4f}")
        # Implied exponent α: |S| = O(N^α), so log(|S|)/log(N) = α
        if S_arr.max() > 0:
            alpha_max = math.log(S_arr.max()) / math.log(N_range)
            alpha_mean = math.log(S_arr.mean()) / math.log(N_range)
            print(f"  Implied exponent: α_max = log(max|S|)/log(N) = {alpha_max:.4f}")
            print(f"                   α_mean = log(mean|S|)/log(N) = {alpha_mean:.4f}")
        print()

    print()

    # Now: ĥ_{r,ℓ}(m) = Σ_ε e_{N_r}(-mε) · S_{r,ℓ,ε}(m)
    # Compute its size
    print("# Empirical |ĥ_{r,ℓ}(m)| analysis (Kalafatelis's combined sum)")
    print(f"  ĥ_{{r,ℓ}}(m) = Σ_{{ε=0,1}} e_{{N_r}}(-mε) · S_{{r,ℓ,ε}}(m)")
    print()
    for r in [2, 3, 4, 5]:
        N_r = 2 * 3**(r-1)
        h_vals = []
        for ell in range(3):
            for m in range(N_r):
                # ĥ = Σ_ε e_{N_r}(-mε) · S_{r,ℓ,ε}(m)
                h_total = complex(0, 0)
                for eps in [0, 1]:
                    S = compute_S(r, ell, eps, m)
                    phase_eps = cmath.exp(-2j * cmath.pi * m * eps / N_r)
                    h_total += phase_eps * S
                h_vals.append(abs(h_total))
        h_arr = np.array(h_vals)
        N_range = 3**(r-1)
        print(f"  r={r}: max |ĥ| = {h_arr.max():.4f},  mean |ĥ| = {h_arr.mean():.4f},  N = {N_range}")
        if h_arr.max() > 0:
            alpha = math.log(h_arr.max()) / math.log(N_range)
            print(f"    max |ĥ| / N = {h_arr.max()/N_range:.4f},  implied α = {alpha:.4f}")
        # ||ĥ||_{ℓ¹(full)} normalized
        l1_norm = h_arr.sum() / 3  # divide by # of ell
        print(f"    ||ĥ||_{{ℓ¹}} (avg over ℓ, sum over m) = {l1_norm:.4f}")
        print(f"    ||ĥ||_{{ℓ¹}} / N_r = {l1_norm/N_r:.4f}")
        print()

    # Save data
    out = os.path.join(OUTDIR, "r78b_S_h_empirical.csv")
    with open(out, 'w', encoding='utf-8') as f:
        f.write("r,N_range,max_S,mean_S,median_S,max_S_over_sqrt_N,alpha_max\n")
        for r in [2, 3, 4, 5]:
            N_phase = 3**(r+1)
            N_range = 3**(r-1)
            N_r = 2 * 3**(r-1)
            S_vals = []
            for ell in range(3):
                for eps in [0, 1]:
                    for m in range(N_r):
                        S_vals.append(abs(compute_S(r, ell, eps, m)))
            S_arr = np.array(S_vals)
            sqrt_N = math.sqrt(N_range)
            alpha_max = math.log(S_arr.max()) / math.log(N_range) if N_range > 1 else 0
            f.write(f"{r},{N_range},{S_arr.max():.6f},{S_arr.mean():.6f},"
                    f"{np.median(S_arr):.6f},{S_arr.max()/sqrt_N:.6f},{alpha_max:.6f}\n")
    print(f"[save] {out}")


if __name__ == "__main__":
    main()
